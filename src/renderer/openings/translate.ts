function translatePart(part: string): string {
  const trimmed = part.trim()
  if (PHRASES_RU[trimmed]) return PHRASES_RU[trimmed]
  if (FAMILY_NAMES_RU[trimmed]) return FAMILY_NAMES_RU[trimmed]
  const suffixMatch = trimmed.match(/^(.+?) (Variation|Attack|Gambit|Defense|System|Line|Countergambit|Counterattack)$/)
  if (suffixMatch) {
    const head = suffixMatch[1]
    const word = WORDS_RU[suffixMatch[2]]
    const translatedHead = PHRASES_RU[head] ?? head
    return `${word.charAt(0).toUpperCase()}${word.slice(1)} ${translatedHead}`
  }
  if (/^with /.test(trimmed)) return trimmed.replace(/^with /, 'с ')
  return trimmed
}

export function translateFamily(family: string): string {
  return FAMILY_NAMES_RU[family] ?? family
}

export function splitOpeningName(name: string): { family: string; variations: string[] } {
  const colon = name.indexOf(':')
  if (colon === -1) return { family: name.trim(), variations: [] }
  return {
    family: name.slice(0, colon).trim(),
    variations: name
      .slice(colon + 1)
      .split(',')
      .map((part) => part.trim())
      .filter(Boolean)
  }
}

export function translateOpeningName(name: string): string {
  const { family, variations } = splitOpeningName(name)
  const familyRu = translateFamily(family)
  if (!variations.length) return familyRu
  return `${familyRu}: ${variations.map(translatePart).join(', ')}`
}
